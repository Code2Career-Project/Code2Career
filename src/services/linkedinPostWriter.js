import { repoById } from '../data/constants.js';
import { LINKEDIN_EVENT_CATEGORIES, classifyEventForLinkedIn } from './linkedinEventClassifier.js';

const PENDING_STATUS = 'Awaiting Approval';
const DRAFT_TONES = ['Professional', 'Technical', 'Achievement-focused', 'Friendly'];

const tag = (skill) => skill.replace(/[^A-Za-z0-9+]/g, '');

function purposeLabel(category) {
  const map = {
    bug_fix: 'Technical Achievement',
    new_feature: 'Project Announcement',
    milestone: 'Development Milestone',
    ui_ux: 'Project Announcement',
    performance: 'Technical Achievement',
  };
  return map[category] || 'Development Milestone';
}

function hashtags(repo, category, skill) {
  const base = (repo?.skills || []).slice(0, 3).map(tag).filter(Boolean);
  const extra = {
    bug_fix: ['Debugging', 'SoftwareEngineering'],
    new_feature: ['FeatureDevelopment'],
    milestone: ['Shipping'],
    ui_ux: ['UX', 'Frontend'],
    performance: ['Performance', 'Architecture'],
  }[category] || [];
  const skillTag = skill ? [tag(skill)] : [];
  return [...new Set([...base, ...extra, ...skillTag].filter(Boolean))].slice(0, 6);
}

function writeBody(event, repo, classification, { variant = 0 } = {}) {
  const name = repo.name;
  const lang = repo.language;
  const stack = (repo.skills || []).slice(0, 4).join(', ');
  const skill = typeof event.metadata?.skill === 'string' && repo.skills.includes(event.metadata.skill)
    ? event.metadata.skill
    : repo.skills[0] || lang;
  const category = classification.category;
  const hook = {
    bug_fix: [
      `Tracked down a stubborn issue in ${name} and landed a focused fix.`,
      `Resolved a reliability problem in ${name} after reviewing the simulated activity log.`,
    ],
    new_feature: [
      `Shipped meaningful feature work on ${name}.`,
      `Extended ${name} with a module that fits the existing ${lang} codebase.`,
    ],
    milestone: [
      `Reached a visible milestone on ${name}.`,
      `${name} just passed an important delivery checkpoint in the demo timeline.`,
    ],
    ui_ux: [
      `Improved the experience on ${name} with deliberate UI work.`,
      `Polished interaction patterns on ${name} while keeping the stack honest: ${stack}.`,
    ],
    performance: [
      `Tightened performance-sensitive paths in ${name}.`,
      `Refined architecture boundaries in ${name} without claiming unverified metrics.`,
    ],
  }[category] || [`Progress update on ${name}.`];
  const open = hook[variant % hook.length];

  const problem = category === 'bug_fix'
    ? `The simulated event "${event.title}" points to a concrete defect area rather than a cosmetic tweak.`
    : `The activity reference is "${event.title}" on repository ${name}.`;

  const approach = category === 'bug_fix'
    ? `The fix stays within technologies already listed on the repository${skill ? `, including ${skill}` : ''}. No invented user counts or latency numbers are included.`
    : category === 'performance'
      ? `Changes stay grounded in ${stack || lang}; this draft does not claim benchmark results.`
      : `Implementation stays aligned with ${stack || lang} skills recorded for this project in Code2Career.`;

  const lesson = category === 'milestone'
    ? 'Lesson: small, verifiable milestones are easier to communicate than vague "big rewrites".'
    : 'Lesson: tie social posts to repository evidence your team can actually review.';

  const footer = 'Generated by Code2Career AI Draft Simulation from simulated GitHub activity — local templates only, not a real AI or LinkedIn API.';

  return [open, problem, approach, lesson, footer].join('\n\n');
}

function writeTitle(event, repo, classification) {
  const name = repo.name;
  const titles = {
    bug_fix: `Fixing a real issue in ${name}`,
    new_feature: `New capability in ${name}`,
    milestone: `Milestone shipped: ${name}`,
    ui_ux: `Design progress on ${name}`,
    performance: `Architecture refinement in ${name}`,
  };
  return titles[classification.category] || `Update from ${name}`;
}

export function writeLinkedInDraftFromEvent(event, repo, classification, options = {}) {
  if (!classification?.qualifies || !repo) return null;
  const variant = options.variant || 0;
  const skill = typeof event.metadata?.skill === 'string' && repo.skills.includes(event.metadata.skill)
    ? event.metadata.skill
    : null;
  const now = event.timestamp || new Date().toISOString();
  const category = classification.category;
  return {
    id: `draft-${event.id}`,
    eventId: event.id,
    repoId: repo.id,
    eventType: event.type,
    eventTitle: event.title,
    eventCategory: category,
    eventCategoryLabel: LINKEDIN_EVENT_CATEGORIES[category] || category,
    purpose: purposeLabel(category),
    title: writeTitle(event, repo, classification),
    body: writeBody(event, repo, classification, { variant }),
    hashtags: hashtags(repo, category, skill),
    tone: DRAFT_TONES.includes(options.tone) ? options.tone : 'Professional',
    status: PENDING_STATUS,
    skill,
    customized: false,
    aiGenerated: true,
    source: options.source || 'github_event',
    alternativeOf: options.alternativeOf || null,
    rejectionReason: '',
    rejectionNotes: '',
    rejectedAt: null,
    createdAt: now,
    updatedAt: now,
    publishedAt: '',
    publishedAs: '',
  };
}

export function draftFromClassifiedEvent(event, repo) {
  const classification = classifyEventForLinkedIn(event, repo);
  if (!classification.qualifies) return { draft: null, classification };
  return {
    draft: writeLinkedInDraftFromEvent(event, repo, classification),
    classification,
  };
}

export function writeAlternativeFromDraft(source) {
  const repo = repoById(source.repoId);
  const event = {
    id: source.eventId || `alt-${source.id}`,
    type: source.eventType || 'feature',
    title: source.eventTitle || source.title,
    description: source.body?.slice(0, 120) || '',
    timestamp: new Date().toISOString(),
    metadata: { skill: source.skill, meaningful: true, linkedinCategory: source.eventCategory },
  };
  const classification = classifyEventForLinkedIn(event, repo);
  if (!classification.qualifies && source.eventCategory) {
    classification.qualifies = true;
    classification.category = source.eventCategory;
  }
  if (!classification.qualifies || !repo) return null;
  const draft = writeLinkedInDraftFromEvent(event, repo, classification, {
    variant: 1,
    alternativeOf: source.id,
    tone: source.tone === 'Professional' ? 'Technical' : 'Professional',
  });
  if (!draft) return null;
  draft.id = `draft-alt-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`;
  draft.eventId = `alt-event-${source.eventId || source.id}`;
  return draft;
}
